export const dict = Object.fromEntries(
  Object.entries(LANG_META).map(([langCode, meta]) => {
    const items = {};
    if (meta.dictKey !== 'vi') {
      for (const [id, translations] of Object.entries(ITEM_TRANSLATIONS)) {
        const text = translations?.[meta.dictKey] || translations?.en;
        if (text) items[id] = text;
      }
    }
    return [langCode, { flag: meta.flag, total: meta.total, thanks: meta.thanks, items }];
  })
);
